// Builds, from the logs of a discovery tour (each mission with actors@, tools/galaxy_tour.mjs), a route that places Mario
// on the visible star of each mission (tp:x;y;z), in the order of Nebula's kGalaxyStages: the star's own code runs (its
// demo, the save, the return to the Observatory) as when it is touched playing, instead of the star@ hook, which only
// asks for the demo and in some stages writes through a null pointer (docs/PROGRESO_AUTONOMO.md, block 23).
// The positions come from the user's disc: the route goes OUTSIDE the repository (it is game data).
//   node tools/make_star_route.mjs <out file> <discovery log>...    (log_end.txt or log_full.txt of the tours)
// Missions with no visible star at the start (it appears after an objective) are listed, not routed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const [out, ...logs] = process.argv.slice(2);
if (!out || logs.length === 0) {
  console.error('usage: node tools/make_star_route.mjs <out file> <discovery log>...');
  process.exit(2);
}

// The visible stars of each mission, as its actors@ listed them
const stars = new Map();
for (const log of logs) {
  let stop = null;
  for (const line of readFileSync(log, 'utf8').split('\n')) {
    let m;
    if ((m = /^\[host\] tour: stop \d+ of \d+, (\S+) scenario (\d+)/.exec(line))) {
      stop = `${m[1]}:${m[2]}`;
      if (!stars.has(stop)) stars.set(stop, []);
    } else if (stop && (m = /^actor (powerstar|grandstar) (-?\d+) (-?\d+) (-?\d+) .*hidden=0/.exec(line))) {
      stars.get(stop).push([Number(m[2]), Number(m[3]), Number(m[4])]);
    }
  }
}

// The missions in story order: kGalaxyStages ("by dome"), the Gateway first, the final battle apart (with graphics)
const header = readFileSync(join(root, 'third_party/nebula/runtime/include/galaxy/gx/galaxy_select.h'), 'utf8');
const galaxies = [...header.matchAll(/\{"(\w+)", (\d+)u\}/g)].map((m) => [m[1], Number(m[2])]).filter(([g]) => g !== 'AstroGalaxy');
const order = ['HeavensDoorGalaxy:1'];
for (const [galaxy, count] of galaxies) {
  if (galaxy === 'KoopaBattleVs3Galaxy') continue;
  for (let n = 1; n <= count; n++) if (!(galaxy === 'HeavensDoorGalaxy' && n === 1)) order.push(`${galaxy}:${n}`);
}

const lines = ['# Generated by tools/make_star_route.mjs from the user\'s disc (game data: keep it out of the repository).'];
const missing = [];
for (const mission of order) {
  const visible = stars.get(mission) || [];
  if (visible.length === 0) {
    missing.push(mission);
    continue;
  }
  const [x, y, z] = visible[0];
  lines.push(`${mission}/tp:${x};${y - 80};${z}@600/wait@2400`); // Mario a little below the star's centre
}
writeFileSync(out, lines.join('\n') + '\n');
console.log(`${order.length} misiones: ${order.length - missing.length} con estrella visible al empezar (en ${out}), ` +
            `${missing.length} sin ella (aparece tras un objetivo): ${missing.join(', ')}`);
