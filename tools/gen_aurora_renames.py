#!/usr/bin/env python3
"""Generates web/aurora/include/aurora_api_renames.h: the C symbols that Aurora's GX/VI API and the game module's
Revolution SDK both define (measured with llvm-nm on the built static libraries), each renamed aurora_<name> in
Aurora. One wasm binary holds both (web/bridge): the game calls its own SDK, which writes the console's FIFO, and
Aurora keeps its whole API, including the internals that share files with the colliding functions (copy_tex, __gx,
vi::configured_fb_size), under other names.

    python3 -I tools/gen_aurora_renames.py <llvm-nm> <libsmg_game.a> <out.h> <aurora .a files...>

The libraries must be built without the renames (a build of web/aurora with -DSMG_AURORA_RENAMES=OFF).
"""
import re
import subprocess
import sys


def defined(nm: str, libs: list) -> set:
    names = set()
    for lib in libs:
        out = subprocess.run([nm, "--defined-only", "-g", lib], capture_output=True, text=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 3 and parts[1] in "TDBRVWCtd":
                names.add(parts[2])
    return names


def main() -> int:
    nm, game, out, *aurora = sys.argv[1:]
    common = sorted(defined(nm, [game]) & defined(nm, aurora))
    bad = [n for n in common if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n) or n.startswith("_Z")]
    if bad:
        sys.exit(f"error: not plain C identifiers, cannot be renamed by macro: {bad[:10]}")
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_aurora_renames.py: Aurora's API symbols the game module's SDK also defines,\n")
        f.write(f"   {len(common)} of them, renamed in every Aurora unit (web/aurora/CMakeLists.txt). Do not edit. */\n")
        f.write("#pragma once\n\n")
        for name in common:
            f.write(f"#define {name} aurora_{name}\n")
    print(f"{out}: {len(common)} renames")
    return 0


if __name__ == "__main__":
    sys.exit(main())
